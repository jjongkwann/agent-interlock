export type Language = "en" | "ko";
export type Message = string | { text: string; values: Array<string | number> };

export const LANGUAGE_STORAGE_KEY = "agent-interlock.studio.language";

export function resolveLanguage(saved: string | null, browserLanguage = "en"): Language {
  return saved === "en" || saved === "ko" ? saved : browserLanguage.toLowerCase().startsWith("ko") ? "ko" : "en";
}

export function message(text: string, ...values: Array<string | number>): Message {
  return { text, values };
}

export function translate(language: Language, value: Message | null | undefined): string {
  if (value == null) return "";
  const text = typeof value === "string" ? value : value.text;
  const translated = language === "ko" && Object.hasOwn(korean, text) ? korean[text] : text;
  return typeof value === "string" ? translated : translated.replace(/\{(\d+)\}/g, (placeholder, index) => String(value.values[Number(index)] ?? placeholder));
}

